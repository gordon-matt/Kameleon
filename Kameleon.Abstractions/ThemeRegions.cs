namespace Kameleon;

/// <summary>
/// Conventional region names, so that pages and themes written by different people line up. Regions are a
/// convention, not a contract: a theme may leave any of them out, reorder them or add regions of its own.
/// </summary>
public static class ThemeRegions
{
    /// <summary>
    /// The header constant.
    /// </summary>
    public const string Header = "Header";
    /// <summary>
    /// The primary navigation constant.
    /// </summary>
    public const string PrimaryNavigation = "PrimaryNavigation";
    /// <summary>
    /// The breadcrumbs constant.
    /// </summary>
    public const string Breadcrumbs = "Breadcrumbs";
    /// <summary>
    /// The hero constant.
    /// </summary>
    public const string Hero = "Hero";
    /// <summary>
    /// The sidebar constant.
    /// </summary>
    public const string Sidebar = "Sidebar";
    /// <summary>
    /// The aside constant.
    /// </summary>
    public const string Aside = "Aside";
    /// <summary>
    /// The footer constant.
    /// </summary>
    public const string Footer = "Footer";
    /// <summary>
    /// The overlay constant.
    /// </summary>
    public const string Overlay = "Overlay";
}
